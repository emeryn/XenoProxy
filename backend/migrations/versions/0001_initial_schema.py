def upgrade() -> None:
    Base.metadata.create_all(bind=op.get_bind())
    _grant_runtime_privileges()


def downgrade() -> None:
    Base.metadata.drop_all(bind=op.get_bind())


def _grant_runtime_privileges() -> None:
    """Give the runtime role data access only, and append-only audit rights."""
    connection = op.get_bind()
    role = connection.exec_driver_sql("SELECT current_setting('xenoproxy.runtime_role', true)").scalar()
    if not role:
        return

    connection.exec_driver_sql(f'GRANT USAGE ON SCHEMA public TO "{role}"')
    connection.exec_driver_sql(
        f'GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO "{role}"'
    )
    connection.exec_driver_sql(f'GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO "{role}"')
    # The audit trail is append-only for the runtime role: no UPDATE, no DELETE.
    connection.exec_driver_sql(f'REVOKE UPDATE, DELETE ON audit_events FROM "{role}"')
