"""Report rendering for incident write-ups."""

from __future__ import annotations

from typing import Any

from app.models.job import Job, ReportStatus

_CSV_INJECTION_PREFIXES = ("=", "+", "-", "@", "\t", "\r")


def neutralise_cell(value: str) -> str:
    """Prefix a spreadsheet cell that a spreadsheet would read as a formula."""
    if value.startswith(_CSV_INJECTION_PREFIXES):
        return f"'{value}"
    return value


def _table(rows: list[tuple[str, str]]) -> str:
    if not rows:
        return "_No data._\n"
    lines = ["| Field | Value |", "| --- | --- |"]
    lines.extend(f"| {key} | {_escape(value)} |" for key, value in rows)
    return "\n".join(lines) + "\n"


def _escape(value: Any) -> str:
    text = str(value if value is not None else "")
    return text.replace("|", "\\|").replace("\n", " ")[:500]


def job_to_markdown(job: Job) -> str:
    """Render a job as a Markdown incident report."""
    summary = job.summary or {}
    parts: list[str] = [
        f"# XenoProxy report — {job.observable_value}",
        "",
        _table(
            [
                ("Observable", job.observable_value),
                ("Type", job.observable_type.value),
                ("Verdict", job.verdict.value.upper()),
                ("Status", job.status.value),
                ("Requested by", job.requested_by_name),
                ("Playbook", job.playbook_name or "—"),
                ("Created", job.created_at.isoformat() if job.created_at else "—"),
                ("Finished", job.finished_at.isoformat() if job.finished_at else "—"),
                ("Job identifier", str(job.id)),
            ]
        ),
        "",
        "## Aggregated findings",
        "",
        _table(
            [
                ("Tags", ", ".join(summary.get("tags") or []) or "—"),
                (
                    "Open ports",
                    ", ".join(str(port) for port in summary.get("open_ports") or []) or "—",
                ),
                ("Known CVEs", ", ".join(summary.get("cves") or []) or "—"),
                ("Hostnames", ", ".join(summary.get("hostnames") or []) or "—"),
                ("Countries", ", ".join(summary.get("countries") or []) or "—"),
                ("Networks", ", ".join(summary.get("asns") or []) or "—"),
                ("Organisations", ", ".join(summary.get("organisations") or []) or "—"),
                (
                    "Detection ratios",
                    ", ".join(
                        f"{name}: {ratio}"
                        for name, ratio in (summary.get("detection_ratios") or {}).items()
                    )
                    or "—",
                ),
                ("Analyzers succeeded", summary.get("analyzers_succeeded", 0)),
                ("Analyzers failed", summary.get("analyzers_failed", 0)),
                ("Served from cache", summary.get("analyzers_from_cache", 0)),
            ]
        ),
        "",
        "## Plugin results",
        "",
    ]

    for report in sorted(job.reports, key=lambda item: (item.plugin_type.value, item.plugin_name)):
        report_summary = report.summary_data or {}
        parts.append(f"### {report.plugin_name} ({report.plugin_type.value})")
        parts.append("")
        rows: list[tuple[str, str]] = [
            ("Status", report.status.value),
            ("Verdict", str(report_summary.get("verdict") or "unknown")),
            ("From cache", "yes" if report.from_cache else "no"),
            ("Duration", f"{report.execution_time_ms or 0} ms"),
        ]
        if report_summary.get("headline"):
            rows.append(("Summary", str(report_summary["headline"])))
        if report_summary.get("detection_ratio"):
            rows.append(("Detection ratio", str(report_summary["detection_ratio"])))
        if report_summary.get("score") is not None:
            rows.append(("Score", str(report_summary["score"])))
        if report_summary.get("tags"):
            rows.append(("Tags", ", ".join(str(tag) for tag in report_summary["tags"])))
        if report.status is ReportStatus.FAILED and report.errors:
            rows.append(("Error", report.errors))
        parts.append(_table(rows))

        for link in report_summary.get("links") or []:
            if isinstance(link, dict) and link.get("url"):
                parts.append(f"- [{link.get('label') or 'Reference'}]({link['url']})")
        parts.append("")

    parts.append("---")
    parts.append("")
    parts.append("Generated by XenoProxy. Raw provider payloads are available in the JSON export.")
    return "\n".join(parts)
